#ifndef FBTEXT_BUFFER
#define FBTEXT_BUFFER FB_BASE
#endif
static volatile u32 *const fb = (volatile u32 *)FBTEXT_BUFFER;
static int line;

static void fill(int y0, int y1, u32 c)
{
	if (y0 < 0) y0 = 0;
	if (y1 > FB_H) y1 = FB_H;
	for (int y = y0; y < y1; y++)
		for (int x = 0; x < FB_W; x++)
			fb[y * FB_W + x] = c;
}

static void draw_char(int col, int row, char ch, u32 fg)
{
	if (col < 0 || col >= COLS || row < 0 || row >= ROWS) return;
	if (ch >= 'a' && ch <= 'z')
		ch -= 32;
	if (ch < 32 || ch >= 96)
		ch = '?';
	const u8 *g = font[ch - 32];
	int x0 = col * CELL_W, y0 = TOP + row * CELL_H;
	for (int r = 0; r < 7; r++)
		for (int c = 0; c < 5; c++) {
			u32 px = (g[r] >> (4 - c)) & 1 ? fg : C_BG;
			for (int dy = 0; dy < SCALE; dy++)
				for (int dx = 0; dx < SCALE; dx++)
					fb[(y0 + r * SCALE + dy) * FB_W + x0 + c * SCALE + dx] = px;
		}
}

/* Écrit à partir de la colonne col, renvoie la colonne suivante. */
static int puts_at(int col, int row, const char *s, u32 fg)
{
	while (*s && col < COLS)
		draw_char(col++, row, *s++, fg);
	return col;
}

static int hex_at(int col, int row, u64 v, int digits, u32 fg)
{
	col = puts_at(col, row, "0X", fg);
	for (int i = digits - 1; i >= 0 && col < COLS; i--)
		draw_char(col++, row, "0123456789ABCDEF"[(v >> (i * 4)) & 0xF], fg);
	return col;
}

static void say(const char *label, u32 fg)
{
	if (line >= ROWS) line = 0;
	fill(TOP + line * CELL_H, TOP + (line + 1) * CELL_H, C_BG);
	puts_at(0, line++, label, fg);
}

static void say_hex(const char *label, u64 v, int digits)
{
	if (line >= ROWS) line = 0;
	fill(TOP + line * CELL_H, TOP + (line + 1) * CELL_H, C_BG);
	int col = puts_at(0, line, label, C_DIM);
	hex_at(col, line++, v, digits, C_FG);
}

static u32 be32(const u8 *p)
{
	return (u32)p[0] << 24 | (u32)p[1] << 16 | (u32)p[2] << 8 | p[3];
}

static u64 be64(const u8 *p)
{
	return (u64)be32(p) << 32 | be32(p + 4);
}

static int starts_with(const char *s, const char *prefix)
{
	while (*prefix)
		if (*s++ != *prefix++)
			return 0;
	return 1;
}

static int str_eq(const char *a, const char *b)
{
	while (*a && *a == *b)
		a++, b++;
	return *a == *b;
}

static u32 align4(u32 v)
{
	return (v + 3) & ~3u;
}

/* Lit 1 ou 2 cellules big-endian. */
static u64 cells(const u8 *p, u32 n)
{
	return n == 2 ? be64(p) : be32(p);
}
